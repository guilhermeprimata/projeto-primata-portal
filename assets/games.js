export function gameUrl(game) {
  if (game.source === 'colecao2') {
    return `${COLECAO2_BASE}${encodeURIComponent(game.slug)}/`;
  }
  return `${QUICKPLAY_BASE}${encodeURIComponent(game.file)}`;
}

export function gameDesc(game, lang) {
  return game.desc?.[lang] || game.desc?.['en-US'] || '';
}
