export function t(lang, key, vars = null) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS[FALLBACK_LANG];
  let value = dict[key] ?? TRANSLATIONS[FALLBACK_LANG][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      value = value.replace(`{${k}}`, String(v));
    }
  }
  return value;
}

export function categoryLabel(lang, category) {
  const map = {
    acao: 'filterAcao',
    estrategia: 'filterEstrategia',
    puzzle: 'filterPuzzle',
    arcade: 'filterArcade',
    simulacao: 'filterSimulacao'
  };
  return t(lang, map[category] || 'filterTodos');
}
