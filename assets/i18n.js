export function normalizeLang(raw) {
  if (!raw || typeof raw !== 'string') return null;
  const tag = raw.trim().toLowerCase().replace(/_/g, '-');
  if (tag === 'pt' || tag.startsWith('pt-')) return 'pt-BR';
  if (tag === 'es' || tag.startsWith('es-')) return 'es-ES';
  if (tag === 'ru' || tag.startsWith('ru-')) return 'ru-RU';
  if (tag === 'zh' || tag.startsWith('zh-')) return 'zh-CN';
  if (tag === 'en' || tag.startsWith('en-')) return 'en-US';
  return null;
}

export function detectInitialLang() {
  try {
    const params = new URLSearchParams(window.location.search);
    const fromUrl = normalizeLang(params.get('lang'));
    if (fromUrl) return fromUrl;
  } catch { /* ignore */ }

  try {
    const saved = normalizeLang(localStorage.getItem(STORAGE_KEY));
    if (saved) return saved;
  } catch { /* ignore */ }

  const browserLangs = Array.isArray(navigator.languages) && navigator.languages.length
    ? navigator.languages
    : [navigator.language || navigator.userLanguage || ''];

  for (const candidate of browserLangs) {
    const match = normalizeLang(candidate);
    if (match) return match;
  }

  return FALLBACK_LANG;
}

export function persistLang(lang) {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch { /* ignore */ }
}

